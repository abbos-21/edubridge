// Extracts the profile-builder data and the demo students from the old minified bundle:
//  - the 36 activity ideas (en/uz), their categories and signal labels
//  - the original rule-based profile check (gz) and idea ranking (yz) as a CommonJS FIXTURE used only by tests,
//    to prove the readable TypeScript port behaves identically
//  - the three demo students (profiles only) and the field-of-study options
import fs from 'fs';

const s = fs.readFileSync(new URL('./EduBridge.bundle.html', import.meta.url), 'utf8');
const BT = String.fromCharCode(96);
const BS = String.fromCharCode(92);

function matchEnd(open) {
  // returns the index just after the bracket/brace/paren matching the one at `open`
  let d = 0, q = null;
  for (let j = open; j < s.length; j++) {
    const c = s[j];
    if (q) { if (c === BS) { j++; continue; } if (c === q) q = null; continue; }
    if (c === '"' || c === "'" || c === BT) { q = c; continue; }
    if (c === '[' || c === '{' || c === '(') d++;
    else if (c === ']' || c === '}' || c === ')') { d--; if (d === 0) return j + 1; }
  }
  throw new Error('unterminated');
}

// ---- ideas + check + rank ------------------------------------------------------------------------------
const geStart = s.indexOf('function ge(e,a,t){const n=(s,r)=>({en:s,uz:r})');
const yzStart = s.indexOf('function yz(e,a){const t={free:0');
const yzEnd = matchEnd(s.indexOf('{', yzStart));
const growthSrc = s.slice(geStart, yzEnd);
const lib = new Function(growthSrc + ';return {jt,Br,hz,mz,pz,gz,yz,ce};')();
console.log('ideas', lib.jt.length, 'categories', Object.keys(lib.Br).length, 'signals', Object.keys(lib.hz).length);

const out = new URL('./', import.meta.url);
const save = (name, v) => fs.writeFileSync(new URL(name, out), JSON.stringify(v, null, 1));
save('growth-ideas.recovered.json', { ideas: lib.jt, categories: lib.Br, signals: lib.hz, minIelts: lib.mz, minGrades: lib.pz });

// the original functions, as a test-only fixture (CommonJS)
fs.mkdirSync(new URL('../../apps/web/tests/fixtures/', import.meta.url), { recursive: true });
fs.writeFileSync(
  new URL('../../apps/web/tests/fixtures/original-growth.cjs', import.meta.url),
  '// GENERATED by data/recovered/extract_growth.mjs from the previous build. Test fixture only: the original rule-based\n' +
    '// profile check (gz) and idea ranking (yz). The TypeScript port in src/lib/growth must behave identically.\n' +
    growthSrc + '\nmodule.exports = { jt, gz, yz };\n',
);

// ---- demo students + defaults -----------------------------------------------------------------------------
const wlStart = s.indexOf('wl={citizenship:"Uzbekistan"');
const fgStart = s.indexOf('Fg=[{key:"A"', wlStart);
const fgEnd = matchEnd(fgStart + 3);
const personasSrc = s.slice(wlStart, fgEnd);
const pers = new Function('const ' + personasSrc + ';return {wl,Fg};')();
console.log('personas', pers.Fg.map((p) => p.key));
save('demo-personas.recovered.json', pers);

// ---- field of study options ---------------------------------------------------------------------------------
const m = /[,;\s]xe=\{(?:computing|business|engineering)/.exec(s);
if (m) {
  const st = s.indexOf('xe={', m.index);
  const end = matchEnd(st + 3);
  const xe = new Function('return ' + s.slice(st + 3, end))();
  console.log('fields', Object.keys(xe));
  save('fields.recovered.json', xe);
} else console.log('xe not found');
